let markdown_cell value =
  value |> String.split_on_char '|' |> String.concat "\\|"
  |> String.split_on_char '\n' |> String.concat "<br>"

let list_cell values = values |> String.concat "; " |> markdown_cell
let option_cell render = function None -> "-" | Some value -> render value

let render_ontology_markdown () =
  let header =
    [
      "# Zellij executable ontology";
      "";
      "Generated from `Zellij_ontology.nodes`. One ontology holon per row.";
      "";
      "| ID | Parent | Level | Kind | Lifecycle | Carrier | Operations | \
       Observations | Invariants | Hazards | Sources | RCA origin | Residuals \
       |";
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|";
    ]
  in
  let rows =
    List.map
      (fun node ->
        Printf.sprintf
          "| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |"
          (markdown_cell (Zellij_ontology.id node))
          (option_cell markdown_cell (Zellij_ontology.parent_id node))
          (Zellij_ontology.level_name (Zellij_ontology.level node))
          (Zellij_ontology.kind_name (Zellij_ontology.kind node))
          (Zellij_ontology.lifecycle_name (Zellij_ontology.lifecycle node))
          (markdown_cell (Zellij_ontology.carrier node))
          (list_cell (Zellij_ontology.operations node))
          (list_cell (Zellij_ontology.observations node))
          (list_cell (Zellij_ontology.invariants node))
          (list_cell (Zellij_ontology.hazards node))
          (list_cell (Zellij_ontology.sources node))
          (match Zellij_ontology.rca_origin node with
          | Specification -> "Specification"
          | Implementation -> "Implementation"
          | Environment -> "Environment"
          | Evidence -> "Evidence"
          | Control -> "Control")
          (list_cell (Zellij_ontology.residuals node)))
      Zellij_ontology.nodes
  in
  String.concat "\n" (header @ rows @ [ "" ])

