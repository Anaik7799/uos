let render_authority_json () =
  let pages =
    List.map
      (fun row ->
        `Assoc
          [
            ("id", `String (Zellij_atlas.id row));
            ("description", `String (Zellij_atlas.description row));
            ( "url",
              match Zellij_atlas.documentation_url row with
              | Some url -> `String url
              | None -> `Null );
            ( "lifecycle",
              `String (Zellij_atlas.lifecycle_name (Zellij_atlas.lifecycle row))
            );
            ( "semantic_credit",
              `String (Zellij_atlas.credit_name (Zellij_atlas.credit row)) );
            ("acquisition_status", `String "discovered-from-official-toc");
            ("content_digest", `Null);
            ( "version_applicability",
              `String
                "current website; installed 0.44.3 applicability not \
                 established" );
          ])
      Zellij_atlas.documentation_pages
  in
  Yojson.Safe.pretty_to_string
    (`Assoc
       [
         ("schema", `String "hermes-zellij-authority-v1");
         ("source_class", `String "external-documentation-oracle");
         ( "inventory_source",
           `String "https://zellij.dev/documentation/toc.html" );
         ("inventory_observed_at", `String "2026-08-13T14:18:00+02:00");
         ("inventory_complete", `Bool true);
         ("atlas_digest", `String Zellij_atlas.digest);
         ("pages", `List pages);
       ])
  ^ "\n"

let render_model_json intent =
  let sessions =
    Zellij_intent.sessions intent
    |> List.map (fun session ->
        let name = Zellij_intent.session_name session in
        `Assoc [ ("command", `String name); ("session", `String name) ])
  in
  Yojson.Safe.pretty_to_string
    (`Assoc
       [
         ("schema", `String "hermes-zellij-model-v1");
         ("intent_digest", `String (Zellij_intent.digest intent));
         ( "intent",
           Yojson.Safe.from_string (Zellij_intent.canonical_json intent) );
         ("atlas_digest", `String Zellij_atlas.digest);
         ("sessions", `List sessions);
       ])
  ^ "\n"
