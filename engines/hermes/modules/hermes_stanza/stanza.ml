module IntSet = Set.Make (Int)

let cone_of targets =
  let seeds = IntSet.of_list targets in
  let reached =
    List.fold_left
      (fun acc t -> List.fold_left (fun a x -> IntSet.add x a) acc (cone t))
      IntSet.empty targets
  in
  IntSet.elements (IntSet.diff reached seeds)

